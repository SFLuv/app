// Package v4s reads public shift availability from a Volunteers for Salesforce
// (V4S) job listing page.
//
// V4S is the Salesforce nonprofit volunteering package. It ships no API — no
// @RestResource, no webservice endpoint — so the only public surface is the
// Visualforce page an organization already exposes on its Salesforce Site. That
// page carries everything we need: for each shift, its id, its start in UTC,
// its length, and how many places are confirmed and still available.
//
// This package parses that page. Parsing someone's HTML is a liability, so two
// things are deliberate:
//
//   - It anchors on the parts of a V4S page that are generated by the package
//     itself rather than by the organization's theme: the JobShiftDateTimeString
//     call the page emits per shift, and the "confirmed: N - available: M" text
//     that ShowNumberAvailable=1 turns on. A site's own styling can change
//     freely without breaking this.
//   - It reports a parse that finds nothing as an error rather than as "no
//     shifts". Silently showing a volunteer "0 spots left" because a page
//     changed shape is worse than showing them nothing.
package v4s

import (
	"errors"
	"fmt"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"time"
)

// Shift is one occurrence of a volunteer job.
type Shift struct {
	// Id is the Salesforce id of the GW_Volunteers__Volunteer_Shift__c record.
	// It is what a deep link to this specific occurrence needs.
	Id string `json:"id"`
	// StartUTC is the shift's start. V4S anchors shifts to the organization's
	// local time, so the UTC instant of a daily shift moves by an hour across a
	// daylight-saving boundary; match on local date, not on this.
	StartUTC time.Time `json:"start_utc"`
	// Hours is the shift's length as the page states it.
	Hours float64 `json:"hours"`
	// Confirmed is how many places the organization has confirmed. It is their
	// staff workflow, not a raw signup count: V4S records a web signup as
	// "Web Sign Up" and someone promotes it later.
	Confirmed int `json:"confirmed"`
	// Available is how many places remain.
	Available int `json:"available"`

	// counted distinguishes "no places left" from "the page never said", so a
	// repeated layout block cannot overwrite real counts with zeroes.
	counted bool
}

// Capacity is the shift's total places, as far as the page lets us infer it.
func (s Shift) Capacity() int { return s.Confirmed + s.Available }

// Full reports whether the shift has no places left.
func (s Shift) Full() bool { return s.Available <= 0 }

var (
	// The page emits this per shift to render the local date client-side: the
	// first argument is the start in UTC, the second the duration in hours.
	//
	// The leading quote-and-capital is load-bearing. V4S also *defines* a
	// function of this name at the top of the page, and matching that
	// definition shifts every shift's fields one row out of step.
	reShiftWhen = regexp.MustCompile(`JobShiftDateTimeString\('([A-Z][^']*)',\s*'([0-9.]+)'\)`)
	// ShowNumberAvailable=1 renders this next to each shift.
	reCounts = regexp.MustCompile(`confirmed:\s*(\d+)\s*-\s*available:\s*(\d+)`)
	// Volunteer Shift ids carry the a1R key prefix.
	reShiftId = regexp.MustCompile(`\b(a1R[a-zA-Z0-9]{12,15})\b`)
)

// ErrNoShifts means the page parsed to nothing recognisable. Treated as a
// failure rather than an empty result: see the package comment.
var ErrNoShifts = errors.New("v4s: no shifts found in the job listing page")

// shiftTimeLayout matches what V4S writes, e.g. "Mon Oct 26 13:30:00 GMT 2026".
const shiftTimeLayout = "Mon Jan 2 15:04:05 MST 2006"

// ParseJobListing extracts every shift from a VolunteersJobListingFS page.
//
// The page renders a shift more than once (it emits both a wide and a narrow
// layout), so results are de-duplicated by shift id, keeping the first
// occurrence that carried counts.
// ParseJobListing extracts every shift from a VolunteersJobListingFS page.
//
// The page lays each shift out as: its id (on the sign-up control), then the
// datetime call, then the availability text — and it emits that group twice,
// once per responsive layout. So this walks the three kinds of token in
// document order and attributes each datetime and count to the id that most
// recently preceded it, which is what the markup actually expresses. Repeated
// groups for the same id collapse into one shift.
func ParseJobListing(page string) ([]Shift, error) {
	if strings.TrimSpace(page) == "" {
		return nil, ErrNoShifts
	}

	type token struct {
		at   int
		kind int // 0 id, 1 when, 2 counts
		m    []string
	}
	tokens := []token{}
	for _, m := range reShiftId.FindAllStringSubmatchIndex(page, -1) {
		tokens = append(tokens, token{at: m[0], kind: 0, m: []string{page[m[2]:m[3]]}})
	}
	for _, m := range reShiftWhen.FindAllStringSubmatchIndex(page, -1) {
		tokens = append(tokens, token{at: m[0], kind: 1, m: []string{page[m[2]:m[3]], page[m[4]:m[5]]}})
	}
	for _, m := range reCounts.FindAllStringSubmatchIndex(page, -1) {
		tokens = append(tokens, token{at: m[0], kind: 2, m: []string{page[m[2]:m[3]], page[m[4]:m[5]]}})
	}
	sort.Slice(tokens, func(i, j int) bool { return tokens[i].at < tokens[j].at })

	order := []string{}
	byId := map[string]*Shift{}
	current := ""

	for _, t := range tokens {
		switch t.kind {
		case 0:
			id := t.m[0]
			if _, ok := byId[id]; !ok {
				byId[id] = &Shift{Id: id}
				order = append(order, id)
			}
			current = id
		case 1:
			if current == "" {
				continue // a datetime before any shift id belongs to nothing
			}
			shift := byId[current]
			if !shift.StartUTC.IsZero() {
				continue // the second layout repeating the same shift
			}
			start, err := time.Parse(shiftTimeLayout, t.m[0])
			if err != nil {
				continue
			}
			shift.StartUTC = start.UTC()
			shift.Hours, _ = strconv.ParseFloat(t.m[1], 64)
		case 2:
			if current == "" {
				continue
			}
			shift := byId[current]
			if shift.counted {
				continue
			}
			shift.Confirmed, _ = strconv.Atoi(t.m[0])
			shift.Available, _ = strconv.Atoi(t.m[1])
			shift.counted = true
		}
	}

	out := make([]Shift, 0, len(order))
	for _, id := range order {
		shift := byId[id]
		// A shift we could not time is not usable: it cannot be matched to one
		// of our occurrences, and guessing would attach a count to the wrong day.
		if shift.StartUTC.IsZero() {
			continue
		}
		out = append(out, *shift)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].StartUTC.Before(out[j].StartUTC) })

	if len(out) == 0 {
		return nil, ErrNoShifts
	}
	return out, nil
}

// Match tolerances for picking one shift out of a day that has several.
const (
	// matchWindow is the furthest an occurrence may sit from a shift and still
	// be considered the same thing at all.
	matchWindow = 2 * time.Hour
	// matchConfident is close enough to be certain on its own, whatever else
	// runs that day. Wide enough that nobody has to transcribe a partner's
	// start time to the minute.
	matchConfident = 45 * time.Minute
	// matchRatio is how much nearer the best candidate must be than the
	// runner-up when it is not within matchConfident. Requiring it to be twice
	// as close refuses an occurrence sitting midway between a morning and an
	// afternoon sitting, where picking either would be a coin toss.
	matchRatio = 2
)

// OnLocalDate returns the only shift on the given local date.
//
// It reports false when the date carries more than one shift, because there is
// no answer in that case — use MatchOccurrence, which has the time to
// disambiguate with. Kept for callers that only ever deal in single-shift days.
func OnLocalDate(shifts []Shift, date time.Time, loc *time.Location) (Shift, bool) {
	sameDay := onDate(shifts, date, loc)
	if len(sameDay) != 1 {
		return Shift{}, false
	}
	return sameDay[0], true
}

// MatchOccurrence finds the shift corresponding to one of our occurrences.
//
// Matching is on the organization's local date first, because V4S anchors a
// recurring shift to local time: the same morning shift is 13:30 UTC in summer
// and 14:30 UTC in winter, so a UTC comparison silently mismatches for part of
// the year.
//
// Where a day holds only one shift, the time is ignored entirely — an affiliate
// does not have to reproduce a partner's start time to be matched. Where a day
// holds several, as a job running a morning and an afternoon sitting does, the
// nearest by time of day wins, provided it is within matchWindow and is clearly
// nearer than the runner-up. If it is not, this returns false: showing no
// availability is correct, and attaching a partner's count to the wrong sitting
// is not.
func MatchOccurrence(shifts []Shift, start time.Time, loc *time.Location) (Shift, bool) {
	if loc == nil {
		loc = time.UTC
	}
	sameDay := onDate(shifts, start, loc)
	switch len(sameDay) {
	case 0:
		return Shift{}, false
	case 1:
		return sameDay[0], true
	}

	type scored struct {
		shift Shift
		off   time.Duration
	}
	ranked := make([]scored, 0, len(sameDay))
	for _, shift := range sameDay {
		off := shift.StartUTC.Sub(start)
		if off < 0 {
			off = -off
		}
		ranked = append(ranked, scored{shift: shift, off: off})
	}
	sort.Slice(ranked, func(i, j int) bool { return ranked[i].off < ranked[j].off })

	best, runnerUp := ranked[0], ranked[1]
	if best.off > matchWindow {
		return Shift{}, false
	}
	// Close enough to be sure on its own.
	if best.off <= matchConfident {
		return best.shift, true
	}
	// Otherwise it has to be decisively nearer than the alternative, or we are
	// guessing which sitting an affiliate meant.
	if runnerUp.off < time.Duration(matchRatio)*best.off {
		return Shift{}, false
	}
	return best.shift, true
}

// onDate returns every shift falling on the given local date.
func onDate(shifts []Shift, date time.Time, loc *time.Location) []Shift {
	if loc == nil {
		loc = time.UTC
	}
	wantY, wantM, wantD := date.In(loc).Date()
	out := []Shift{}
	for _, shift := range shifts {
		y, m, d := shift.StartUTC.In(loc).Date()
		if y == wantY && m == wantM && d == wantD {
			out = append(out, shift)
		}
	}
	return out
}

// JobListingURL builds the listing URL for a job on a V4S site.
//
// months bounds how far ahead to read; V4S defaults to the current month plus
// two, which is more page than a single occurrence needs.
func JobListingURL(site string, jobId string, months int) string {
	site = strings.TrimRight(strings.TrimSpace(site), "/")
	if months < 1 {
		months = 1
	}
	return fmt.Sprintf(
		"%s/GW_Volunteers__VolunteersJobListingFS?jobId=%s&ShowNumberAvailable=1&nMonthsToShow=%d",
		site, jobId, months,
	)
}

// ShiftSignupURL deep links to one shift's signup form.
func ShiftSignupURL(site string, jobId string, shiftId string) string {
	site = strings.TrimRight(strings.TrimSpace(site), "/")
	return fmt.Sprintf(
		"%s/GW_Volunteers__VolunteersJobListingFS?jobId=%s&volunteerShiftId=%s&ShowNumberAvailable=1",
		site, jobId, shiftId,
	)
}
